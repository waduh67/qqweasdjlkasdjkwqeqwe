async function choose(page: Page, label: string, name: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.getByRole('option', { name, exact: true }).click()
}
async function switchAccount(page: Page, account: { readonly email: string; readonly password: string }) {
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await login(page, account)
}
async function requestResponse(page: Page, path: string, label: string) {
  const received = page.waitForResponse(response => new URL(response.url()).pathname === path && response.request().method() === 'POST')
  await page.getByRole('button', { name: label, exact: true }).click()
  const response = await received
  expect(response.ok()).toBeTruthy()
  return referenceRequest(await response.json())
}

