      if (!stock) throw new Error('Missing available warehouse stock')
      await choose(page, 'Stok penyerahan 1', [stock.skuName, 'Tanpa serial', formatBaseQuantity(stock.quantityBase, stock.baseUnit) + ' m', stock.stockIdentityId.slice(-8)].join(' · '))
