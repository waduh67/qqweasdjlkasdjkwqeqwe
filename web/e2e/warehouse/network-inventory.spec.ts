import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { record, uuid } from '../../src/api/warehouse/codec'
import { decodeClientNetwork, decodeIp, decodeVendor } from '../../src/api/networkModels'
import { captureReferenceThemes, referenceTenant } from './reference-setup'
import { login } from './helpers'

test('vendor inventory and multiple IP allocation follow client review and role access', async ({ page }, info) => {
  test.setTimeout(240_000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const tenant = await referenceTenant(page, 'network')
  const ne = await tenant.createMember('Teknisi NE')
  const fo = await tenant.createMember('Teknisi FO')
  const manager = await tenant.createMember('Manager')
  await login(page, tenant.owner)
  await page.goto('/network-vendors')
  await expect(page.getByRole('heading', { name: 'Vendor Jaringan', exact: true })).toBeVisible()
  await captureReferenceThemes(page, info, 'vendors-empty')
  await page.getByRole('button', { name: 'Tambah vendor', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nama vendor', exact: true }).fill('Metro Telkom')
  await page.getByLabel('Kontak vendor', { exact: true }).fill('NOC Telkom')
  await captureReferenceThemes(page, info, 'vendor-form')
  await page.getByRole('button', { name: 'Tinjau + buat', exact: true }).click()
  await captureReferenceThemes(page, info, 'vendor-review')
  const vendorSaved = page.waitForResponse(r => r.url().endsWith('/network-inventory/vendors') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Simpan', exact: true }).click()
  const vendor = decodeVendor(await (await vendorSaved).json())
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const backup = decodeVendor(await tenant.command('/api/v1/network-inventory/vendors', { name: 'MyRepublic', contact: '', notes: '', active: true, expectedRevision: 0 }))
  await page.goto('/network-ips')
  await captureReferenceThemes(page, info, 'ip-empty')
  await page.getByRole('button', { name: 'Tambah IP public', exact: true }).click()
  await page.getByRole('textbox', { name: 'Alamat IP public', exact: true }).fill('157.15.122.100')
  await page.getByLabel('Subnet mask', { exact: true }).fill('255.255.255.248')
  await page.getByLabel('Gateway', { exact: true }).fill('157.15.122.99')
  await expect(page.getByLabel('Vendor IP', { exact: true }).locator('option')).toContainText(['Tanpa vendor', 'Metro Telkom', 'MyRepublic'])
  await page.getByLabel('Vendor IP', { exact: true }).selectOption(vendor.id)
  await captureReferenceThemes(page, info, 'ip-form')
  await page.getByRole('button', { name: 'Tinjau + buat', exact: true }).click()
  await captureReferenceThemes(page, info, 'ip-review')
  const ipSaved = page.waitForResponse(r => r.url().endsWith('/network-inventory/ips') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Simpan', exact: true }).click()
  const first = decodeIp(await (await ipSaved).json())
  await expect(page.getByRole('dialog')).toHaveCount(0)
  let last = first
  for (let host = 101; host <= 121; host++) last = decodeIp(await tenant.command('/api/v1/network-inventory/ips', { address: '157.15.122.' + host, subnet: '255.255.255.248', gateway: '157.15.122.99', vendorId: vendor.id, notes: '', expectedRevision: 0 }))
  await page.reload()
  await page.getByLabel('Filter vendor', { exact: true }).selectOption(backup.id)
  await expect(page.getByText('Belum ada IP yang sesuai.', { exact: false })).toBeVisible()
  await page.getByLabel('Filter vendor', { exact: true }).selectOption(vendor.id)
  await expect(page.getByRole('button', { name: first.address, exact: true })).toBeVisible()
  await captureReferenceThemes(page, info, 'ip-inventory')
  await page.goto('/b2b/clients')
  await page.getByRole('button', { name: 'Tambah client B2B', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nama client', exact: true }).fill('Harper QA')
  await page.getByRole('textbox', { name: 'Alamat', exact: true }).fill('Jl. Hotel Harper')
  await page.getByRole('textbox', { name: 'Kontak / PIC', exact: true }).fill('PIC Harper')
  await captureReferenceThemes(page, info, 'client-basics')
  await page.getByRole('button', { name: 'Berikutnya: Kunjungan', exact: true }).click()
  await page.getByRole('button', { name: 'Pilih', exact: true }).click()
  await captureReferenceThemes(page, info, 'client-visits')
  await page.getByRole('button', { name: 'Berikutnya: Koneksi', exact: true }).click()
  await page.getByLabel('Nama PIC', { exact: true }).fill('Reza')
  await page.getByLabel('No. HP PIC', { exact: true }).fill('08123456789')
  await page.getByLabel('Bandwidth mainlink (Mbps)', { exact: true }).fill('100')
  await page.getByLabel('Infrastruktur mainlink', { exact: true }).selectOption('PARTNER')
  await page.getByRole('combobox', { name: 'Vendor mainlink', exact: true }).selectOption(vendor.id)
  await page.getByLabel('Last mile / layanan mainlink', { exact: true }).fill('Metro Telkom')
  await page.getByLabel('ID pelanggan mainlink', { exact: true }).fill('TELKOM-123')
  await page.getByLabel('Bandwidth backup (Mbps)', { exact: true }).fill('100')
  await page.getByLabel('Vendor backup', { exact: true }).selectOption(backup.id)
  await page.getByLabel('ID pelanggan backup', { exact: true }).fill('MYREP-123')
  await captureReferenceThemes(page, info, 'client-network')
  await page.getByRole('button', { name: 'Berikutnya: IP public', exact: true }).click()
  await page.getByLabel('Cari IP tersedia', { exact: true }).fill(first.address)
  await page.getByRole('button', { name: 'Pilih IP', exact: true }).click()
  await page.getByLabel('Cari IP tersedia', { exact: true }).fill('')
  await page.getByRole('navigation', { name: 'Halaman data', exact: true }).getByRole('button', { name: 'Berikutnya', exact: true }).click()
  await page.getByLabel('Cari IP tersedia', { exact: true }).fill(last.address)
  await page.getByRole('button', { name: 'Pilih IP', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Lepas IP ' + first.address, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Lepas IP ' + last.address, exact: true })).toBeVisible()
  await page.getByLabel('Subnet mask', { exact: true }).fill('255.255.255.248')
  await page.getByLabel('Gateway', { exact: true }).fill('157.15.122.99')
  await page.getByLabel('DNS', { exact: true }).fill('157.15.122.122, 8.8.8.8')
  await captureReferenceThemes(page, info, 'client-allocation')
  await page.getByRole('button', { name: 'Berikutnya: Tunnel', exact: true }).click()
  await page.getByLabel('Dial tunnel', { exact: true }).fill('157.15.122.255')
  await page.getByLabel('Username tunnel', { exact: true }).fill('qa-tunnel')
  await page.getByLabel('Password tunnel baru', { exact: true }).fill('synthetic-qa-secret')
  await page.getByLabel('Remote address tunnel', { exact: true }).fill('157.15.122.87')
  await page.getByLabel('Local address tunnel', { exact: true }).fill('157.15.122.50')
  await page.getByLabel('Catatan jaringan', { exact: true }).fill('Jaringan hotel QA')
  await captureReferenceThemes(page, info, 'client-tunnel')
  await page.getByRole('button', { name: 'Tinjau + buat', exact: true }).click()
  await expect(page.getByText(first.address + ', ' + last.address, { exact: true })).toBeVisible()
  await expect(page.getByText('synthetic-qa-secret', { exact: true })).toHaveCount(0)
  await captureReferenceThemes(page, info, 'client-review')
  await page.getByRole('tab', { name: 'IP public', exact: true }).click()
  await expect(page.getByLabel('DNS', { exact: true })).toHaveValue('157.15.122.122, 8.8.8.8')
  await expect(page.getByRole('button', { name: 'Lepas IP ' + first.address, exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Tinjau + buat', exact: true }).click()
  const created = page.waitForResponse(r => r.url().endsWith('/api/v1/b2b/clients') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Simpan', exact: true }).click()
  const client = record(await (await created).json()), clientId = uuid(client.id)
  const network = decodeClientNetwork(client.network)
  expect(network.publicIps.map(ip => ip.id)).toEqual(expect.arrayContaining([first.id, last.id]))
  expect(network.tunnelPasswordSet).toBe(true)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/network-ips')
  await page.getByLabel('Filter status IP', { exact: true }).selectOption('ALLOCATED')
  await expect(page.getByRole('button', { name: 'Harper QA', exact: true })).toHaveCount(2)
  await captureReferenceThemes(page, info, 'ip-allocated')
  await page.getByRole('button', { name: first.address, exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Alamat IP public', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Vendor IP', { exact: true })).toBeDisabled()
  await captureReferenceThemes(page, info, 'ip-allocated-form')
  await page.getByRole('button', { name: 'Tutup', exact: true }).last().click()
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await login(page, ne.account)
  await page.goto('/network-ips')
  await expect(page.getByRole('button', { name: 'Tambah IP public', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Harper QA', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Jaringan · Harper QA', exact: true })).toBeVisible()
  await expect(page.getByText('Tersimpan (disembunyikan)', { exact: true })).toBeVisible()
  await expect(page.getByText('Metro Telkom', { exact: true }).last()).toBeVisible()
  await captureReferenceThemes(page, info, 'ne-client-detail')
  for (const member of [ne, manager]) {
    const write = await page.request.post('/api/v1/network-inventory/vendors', { headers: { ...member.headers, 'Idempotency-Key': randomUUID() }, data: { name: 'Forbidden', expectedRevision: 0 } })
    expect(write.status()).toBe(403)
  }
  expect((await page.request.get('/api/v1/network-inventory/ips', { headers: fo.headers })).status()).toBe(403)
  await page.getByRole('button', { name: 'Tutup', exact: true }).last().click()
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await login(page, tenant.owner)
  await page.goto('/b2b/clients')
  await page.getByRole('button', { name: 'Harper QA', exact: true }).click()
  await page.getByRole('tab', { name: 'IP public', exact: true }).click()
  await page.getByRole('button', { name: 'Lepas IP ' + last.address, exact: true }).click()
  await page.getByRole('tab', { name: 'Tunnel', exact: true }).click()
  await expect(page.getByLabel('Password tunnel baru', { exact: true })).toHaveValue('')
  await page.getByLabel('Password tersimpan', { exact: true }).selectOption('clear')
  await page.getByRole('button', { name: 'Tinjau + simpan', exact: true }).click()
  await expect(page.getByText('Akan dihapus', { exact: true })).toBeVisible()
  const updated = page.waitForResponse(r => r.url().endsWith('/api/v1/b2b/clients/' + clientId) && r.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Simpan', exact: true }).click()
  const released = decodeClientNetwork(record(await (await updated).json()).network)
  expect(released.publicIps.map(ip => ip.id)).toEqual([first.id])
  expect(released.tunnelPasswordSet).toBe(false)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/network-ips')
  await page.getByLabel('Filter status IP', { exact: true }).selectOption('AVAILABLE')
  await page.getByLabel('Cari IP / pelanggan', { exact: true }).fill(last.address)
  await expect(page.getByRole('button', { name: last.address, exact: true })).toBeVisible()
  await expect(page.locator('.badge').filter({ hasText: /^Tersedia$/ })).toBeVisible()
  await captureReferenceThemes(page, info, 'ip-released')
})
