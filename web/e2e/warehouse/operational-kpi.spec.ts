import { expect, test } from '@playwright/test'
import { dailyReport, technicianKpi } from '../../src/api/field'
import { workType } from '../../src/api/warehouse/reference'
import { login, selectNamed } from './helpers'
import { captureReferenceDocument, captureReferenceThemes as captureThemes, referenceTenant } from './reference-setup'

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64')

function operationalDate() {
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Jakarta', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(new Date())
  return ['year', 'month', 'day'].map(type => parts.find(part => part.type === type)?.value).join('-')
}
const currentMonth = () => operationalDate().slice(0, 7)

test('NE and FO report daily work; owner reviews immutable evidence, scoped KPI and calendar', async ({ page }, info) => {
  test.setTimeout(360_000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const s = await referenceTenant(page, 'field-kpi')
  const ne = await s.createMember('Teknisi NE'), fo = await s.createMember('Teknisi FO')
  await s.activate()
  await login(page, ne.account)
  await page.goto('/daily-reports')
  await expect(page.getByRole('button', { name: 'Kirim pagi', exact: true })).toBeVisible({ timeout: 45_000 })
  await expect(page.getByRole('combobox', { name: 'Teknisi', exact: true }).getByRole('option')).toHaveCount(2)
  await captureThemes(page, info, 'daily-empty')
  let firstReport: ReturnType<typeof dailyReport> | undefined
  for (const slot of ['pagi', 'sore', 'pagi'] as const) {
    const revision = slot === 'pagi' && firstReport !== undefined
    await page.getByRole('button', { name: (revision ? 'Revisi ' : 'Kirim ') + slot, exact: true }).click()
    await page.getByRole('textbox', { name: 'Catatan pekerjaan', exact: true }).fill(revision ? 'Revisi pemeriksaan NE' : 'Pemeriksaan NE ' + slot)
    await page.locator('input[type=file]').setInputFiles({ name: 'proof.png', mimeType: 'image/png', buffer: png })
    await page.getByRole('button', { name: revision ? 'Tinjau + simpan' : 'Tinjau + buat', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Tinjau laporan harian', exact: true })).toBeVisible()
    await captureReferenceDocument(page, info, 'daily-review-' + slot + (revision ? '-revision' : ''))
    const saved = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/field/reports' && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Kirim laporan', exact: true }).click()
    const response = await saved
    expect(response.status()).toBe(201)
    if (!firstReport) firstReport = dailyReport(await response.json())
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Revisi ' + slot, exact: true })).toBeVisible({ timeout: 45_000 })
  }
  if (!firstReport) throw new Error('Daily report was not created')
  const privatePath = '/api/v1/field/reports/' + firstReport.id + '/revisions/1/photos/' + firstReport.photos[0]?.id
  expect((await page.request.get(privatePath, { headers: fo.headers })).status()).toBe(404)
  for (const name of ['Terkirim · Revisi 2', 'Terkirim · Revisi 1', 'Revisi pagi', 'Revisi sore']) {
    const button = page.getByRole('button', { name, exact: true })
    expect(await button.evaluate(element => {
      const cell = element.closest('.warehouse-cell-value')
      if (!cell) return false
      const control = element.getBoundingClientRect(), bounds = cell.getBoundingClientRect()
      return control.left >= bounds.left - 1 && control.right <= bounds.right + 1
    }), name + ' remains inside its table cell').toBeTruthy()
  }
  await captureThemes(page, info, 'daily-reported')
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await login(page, fo.account)
  await page.goto('/daily-reports')
  await expect(page.getByRole('button', { name: 'Kirim pagi', exact: true })).toBeVisible({ timeout: 45_000 })
  await page.getByRole('button', { name: 'Kirim pagi', exact: true }).click()
  await page.getByRole('textbox', { name: 'Catatan pekerjaan', exact: true }).fill('Pemeriksaan FO')
  await page.getByRole('button', { name: 'Tinjau + buat', exact: true }).click()
  await page.getByRole('button', { name: 'Kirim laporan', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await login(page, s.owner)
  await page.goto('/daily-reports')
  await expect(page.getByText('2 teknisi · Pagi 2 · Sore 1', { exact: false })).toBeVisible({ timeout: 45_000 })
  await expect(page.getByRole('button', { name: 'Kirim pagi', exact: true })).toHaveCount(0)
  await selectNamed(page, 'Teknisi', ne.user.name + ' · NE')
  await expect(page.getByText('1 teknisi · Pagi 1 · Sore 1', { exact: false })).toBeVisible({ timeout: 45_000 })
  await expect(page.getByRole('combobox', { name: 'Teknisi', exact: true }).getByRole('option')).toHaveCount(3)
  await page.getByRole('button', { name: 'Terkirim · Revisi 2', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisi 1', exact: true })).toBeVisible()
  const proof = page.getByAltText('Bukti laporan revisi 1 foto 1')
  await expect.poll(() => proof.evaluate(img => img instanceof HTMLImageElement && img.complete && img.naturalWidth > 0)).toBeTruthy()
  await captureThemes(page, info, 'daily-timeline')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/kpi')
  await expect(page.getByRole('meter')).toHaveCount(2, { timeout: 45_000 })
  await selectNamed(page, 'Tim teknisi', 'Teknisi FO')
  await expect(page.getByRole('meter')).toHaveCount(1, { timeout: 45_000 })
  const filtered = technicianKpi(await s.get('/api/v1/field/kpi?month=' + currentMonth() + '&team=FO'))
  await expect(page.getByRole('meter')).toHaveAttribute('aria-valuenow', String(filtered.average))
  await captureThemes(page, info, 'kpi-fo')
  await page.getByRole('button', { name: /% · Detail$/ }).click()
  await expect(page.getByRole('heading', { name: 'WO overdue (0)', exact: true })).toBeVisible()
  await captureThemes(page, info, 'kpi-fo-detail')
  await page.keyboard.press('Escape')
  await selectNamed(page, 'Tim teknisi', 'Teknisi NE')
  await expect(page.getByRole('meter')).toHaveCount(1, { timeout: 45_000 })
  await page.getByRole('button', { name: /% · Detail$/ }).click()
  await expect(page.getByRole('heading', { name: 'Client dan target visit', exact: true })).toBeVisible()
  await captureThemes(page, info, 'kpi-ne-detail')
  await page.keyboard.press('Escape')
  await page.getByLabel('Bulan KPI').fill('')
  await expect(page.getByText('Pilih bulan untuk melihat KPI', { exact: true })).toBeVisible()
  await expect(page.getByRole('meter')).toHaveCount(0)
  await page.getByLabel('Bulan KPI').fill(currentMonth())
  await page.goto('/warehouse/settings')
  await page.getByRole('tab', { name: 'KPI', exact: true }).click()
  await page.getByRole('button', { name: 'Ubah target KPI', exact: true }).click()
  await page.getByLabel('Batas jumlah WO overdue').fill('5')
  await page.getByLabel('Target poin PSB / Project FO').fill('18')
  await page.getByRole('button', { name: 'Tinjau + simpan', exact: true }).click()
  await captureThemes(page, info, 'settings-kpi-review')
  await page.getByRole('button', { name: 'Simpan setelan', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('18 poin per bulan', { exact: true })).toBeVisible()
  await captureThemes(page, info, 'settings-kpi')
  await page.getByRole('tab', { name: 'Kalender kerja', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Tambah hari libur', exact: true })).toBeVisible({ timeout: 45_000 })
  await page.getByRole('button', { name: 'Tambah hari libur', exact: true }).click()
  await page.getByLabel('Tanggal hari libur').fill(operationalDate())
  await page.getByRole('textbox', { name: 'Nama hari libur', exact: true }).fill('Libur operasional QA')
  await page.getByRole('button', { name: 'Tinjau + buat', exact: true }).click()
  await captureThemes(page, info, 'settings-calendar-review')
  await page.getByRole('button', { name: 'Simpan hari libur', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('gridcell', { name: 'Libur operasional QA', exact: true })).toBeVisible({ timeout: 45_000 })
  await captureThemes(page, info, 'settings-calendar')
  await page.goto('/work-orders/types')
  await page.getByRole('button', { name: 'Jenis baru', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nama jenis pekerjaan', exact: true }).fill('Project FO QA')
  await selectNamed(page, 'Kategori pekerjaan', 'Pemeliharaan')
  await selectNamed(page, 'Kategori KPI', 'Project (3 poin)')
  await page.getByRole('textbox', { name: 'Nama foto wajib', exact: true }).fill('Hasil pekerjaan')
  await captureThemes(page, info, 'work-type-kpi-editor')
  await page.getByRole('button', { name: 'Tinjau jenis', exact: true }).click()
  await expect(page.getByText('KPI: Project (3 poin)', { exact: true })).toBeVisible()
  await captureThemes(page, info, 'work-type-kpi-review')
  const typeSaved = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v2/work-orders/types' && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Simpan jenis', exact: true }).click()
  const typeResponse = await typeSaved
  expect(typeResponse.status()).toBe(201)
  expect(workType(await typeResponse.json()).kpiCategory).toBe('PROJECT')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('Project (3 poin)', { exact: true })).toBeVisible()
  await captureThemes(page, info, 'work-type-kpi-saved')
  await page.goto('/')
  await page.getByRole('tab', { name: 'KPI Teknisi', exact: true }).click()
  await expect(page.getByRole('meter')).toHaveCount(2, { timeout: 45_000 })
  await captureThemes(page, info, 'dashboard-kpi')
})
