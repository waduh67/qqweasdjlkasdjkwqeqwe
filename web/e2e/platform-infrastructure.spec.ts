const evidenceDir = process.env.FTTH_PLATFORM_QA_EVIDENCE_DIR

async function capture(page: Page, name: string) {
  await page.evaluate(async () => { await document.fonts.ready; await new Promise(requestAnimationFrame) })
  const geometry = await page.evaluate(() => {
    const visible = (element: Element) => !element.closest('[hidden], [inert]') && element.getBoundingClientRect().width > 0
    const fields = [...document.querySelectorAll('.horizontal-form .app-field')].filter(visible).map(field => {
      const label = field.querySelector('label'), control = field.querySelector('input,select,[role=combobox]')
      const l = label?.getBoundingClientRect(), c = control?.getBoundingClientRect()
      return { label: label?.textContent, labelLeft: l?.left, labelTop: l?.top, labelBottom: l?.bottom,
        controlLeft: c?.left, controlTop: c?.top, controlRight: c?.right }
    })
    return { width: innerWidth, height: innerHeight, documentWidth: document.documentElement.scrollWidth, fields,
      surfaces: [...document.querySelectorAll('.resource-form-content,.settings-page')].filter(visible).map(element => ({
        width: element.clientWidth, scrollWidth: element.scrollWidth, right: element.getBoundingClientRect().right })) }
  })
  expect(geometry.documentWidth).toBeLessThanOrEqual(geometry.width)
  for (const surface of geometry.surfaces) expect(surface.scrollWidth).toBeLessThanOrEqual(surface.width + 1)
  for (const field of geometry.fields) {
    if (field.controlRight !== undefined) expect(field.controlRight).toBeLessThanOrEqual(geometry.width + 1)
  }
  if (evidenceDir) {
    await mkdir(evidenceDir, { recursive: true })
    await page.screenshot({ path: path.join(evidenceDir, name + '.png'), animations: 'disabled' })
    await writeFile(path.join(evidenceDir, name + '.json'), JSON.stringify(geometry, null, 2))
  }
}

