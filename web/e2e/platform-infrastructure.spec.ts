test('ACS saved testing, discard, failure, busy and retry preserve the draft', async ({ page }) => {
  const fixture = await installInfrastructureRoutes(page)
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.goto('/platform/acs')
  const nbi = page.getByRole('textbox', { name: 'NBI URL', exact: false })
  const testSaved = page.getByRole('button', { name: 'Uji koneksi tersimpan', exact: true })
  const save = page.getByRole('button', { name: 'Simpan setelan', exact: true })
  await expect(nbi).toHaveValue(fixture.acs().nbiUrl)
  await testSaved.click()
  await expect(page.getByText('API ACS terjangkau', { exact: true })).toBeVisible()
  await capture(page, 'acs-test-success')
  await nbi.fill('https://new-api.example.test')
  await expect(testSaved).toBeDisabled()
  await capture(page, 'acs-dirty')
  await page.getByRole('button', { name: 'Buang perubahan', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Buang perubahan ACS?' })).toBeVisible()
  await capture(page, 'acs-discard')
  await page.getByRole('dialog').getByRole('button', { name: 'Buang perubahan', exact: true }).click()
  await expect(nbi).toHaveValue(fixture.acs().nbiUrl)
  await nbi.fill('https://new-api.example.test')
  fixture.failSave(true)
  await save.click()
  await expect(page.getByText('Gagal menyimpan ACS sintetis', { exact: true })).toBeVisible()
  await expect(nbi).toHaveValue('https://new-api.example.test')
  await capture(page, 'acs-save-error')
  fixture.failSave(false)
  const release = fixture.deferSave()
  await save.evaluate(button => {
    if (!(button instanceof HTMLButtonElement)) throw new Error('Save control must be a button')
    button.click(); button.click()
  })
  await expect(nbi).toBeDisabled()
  await expect(testSaved).toBeDisabled()
  await capture(page, 'acs-saving')
  expect(fixture.events.filter(event => event.method === 'PUT' && event.path === '/api/platform/acs-settings')).toHaveLength(2)
  release()
  await expect(nbi).toBeEnabled()
  await expect(page.getByText('Konfigurasi tersimpan', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Password API', exact: true })).toHaveValue('')
  await capture(page, 'acs-saved')
  await testSaved.click()
  const testEvent = fixture.events.filter(event => event.path === '/api/platform/acs-settings/test').at(-1)
  expect(testEvent?.body).toEqual({})
  fixture.failLoad(true)
  await page.reload()
  await expect(page.getByText('Setelan ACS gagal dimuat.', { exact: true })).toBeVisible()
  await capture(page, 'acs-load-error')
  fixture.failLoad(false)
  await page.getByRole('button', { name: 'Coba lagi', exact: true }).click()
  await expect(nbi).toHaveValue('https://new-api.example.test')
})

