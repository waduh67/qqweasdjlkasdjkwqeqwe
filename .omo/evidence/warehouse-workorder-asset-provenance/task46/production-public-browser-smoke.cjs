// Real public UI smoke after activation; auth sessions only, no business data writes.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { chromium } = require('../warehouse-regression-validation/web/node_modules/playwright');
process.umask(0o077);
const base = __dirname;
const activation = JSON.parse(fs.readFileSync(path.join(base, 'production-activation-local.json'), 'utf8'));
if (activation.status !== 'PASS') throw new Error('Actual production activation must pass first');
const environment = Object.fromEntries(fs.readFileSync(path.join(base, 'production-foundation-private/.env'), 'utf8').trim().split('\n').map(line => { const n = line.indexOf('='); return [line.slice(0, n), line.slice(n + 1)]; }));
const evidence = path.join(base, 'public-browser-' + crypto.randomBytes(6).toString('hex'));
fs.mkdirSync(evidence, { mode: 0o700 });
fs.writeFileSync(path.join(base, 'public-browser-latest.txt'), evidence + '\n');
const report = { status: 'RUNNING', startedAtUtc: new Date().toISOString(), domain: 'ftth.karuhundeveloper.com', viewports: [1280, 390], testedCodeCommit: activation.testedCodeCommit, testScope: 'Real public UI login, dashboard, browser reload/session refresh, responsive rendering and logout' };
(async () => {
  let browser;
  try {
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, ignoreHTTPSErrors: false });
    const page = await context.newPage();
    page.setDefaultTimeout(30000);
    const pageErrors = [];
    const afterLoginApiErrors = [];
    const businessMutationRequests = [];
    let authenticated = false;
    page.on('pageerror', error => pageErrors.push(error.message));
    page.on('request', request => { const pathname = new URL(request.url()).pathname; if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method()) && pathname.startsWith('/api/') && !['/api/auth/login', '/api/auth/refresh', '/api/auth/logout'].includes(pathname)) businessMutationRequests.push({ method: request.method(), path: pathname }); });
    page.on('response', response => { if (authenticated && new URL(response.url()).pathname.startsWith('/api/') && response.status() >= 400) afterLoginApiErrors.push({ path: new URL(response.url()).pathname, status: response.status() }); });
    const document = await page.goto('https://ftth.karuhundeveloper.com/login', { waitUntil: 'domcontentloaded' });
    if (document.status() !== 200) throw new Error('Public login document did not return200');
    await page.getByLabel(/^Email\s*\*?$/).fill(environment.FTTH_PLATFORM_ADMIN_EMAIL);
    await page.getByLabel(/^Password\s*\*?$/).fill(environment.FTTH_PLATFORM_ADMIN_PASSWORD);
    const loginResponse = page.waitForResponse(r => new URL(r.url()).pathname === '/api/auth/login' && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Masuk', exact: true }).click();
    const response = await loginResponse;
    const user = (await response.json()).user;
    if (response.status() !== 200 || !user.platformAdmin || user.email !== environment.FTTH_PLATFORM_ADMIN_EMAIL) throw new Error('Public UI login identity mismatch');
    authenticated = true;
    await page.waitForURL('https://ftth.karuhundeveloper.com/platform');
    await page.getByText('Ringkasan platform SaaS — portofolio tenant & langganan.', { exact: true }).waitFor();
    await page.getByText('Belum ada tenant. Onboarding tenant pertama untuk mulai.', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(evidence, 'platform-desktop.png'), fullPage: true });
    report.desktopLoginAndDashboardPassed = true;
    const refreshed = page.waitForResponse(r => new URL(r.url()).pathname === '/api/auth/refresh' && r.request().method() === 'POST');
    await page.reload({ waitUntil: 'domcontentloaded' });
    if ((await refreshed).status() !== 200) throw new Error('Browser refresh token exchange failed');
    await page.getByText('Ringkasan platform SaaS — portofolio tenant & langganan.', { exact: true }).waitFor();
    report.browserReloadAndSessionRefreshPassed = true;
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Keluar', exact: true }).waitFor();
    // Viewport resizing starts the real CSS drawer transition; inspect its settled state.
    await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
    const navToggle = page.getByRole('button', { name: 'Ciutkan sidebar', exact: true });
    await navToggle.click();
    await page.getByRole('button', { name: 'Tutup menu', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().left >= -1);
    await navToggle.click();
    await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
    if (!(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))) throw new Error('Mobile page overflows viewport');
    report.mobileDrawerOpenClosePassed = true;
    await page.screenshot({ path: path.join(evidence, 'platform-mobile.png'), fullPage: true, animations: 'disabled' });
    report.mobileRenderPassed = true;
    const loggedOut = page.waitForResponse(r => new URL(r.url()).pathname === '/api/auth/logout' && r.request().method() === 'POST');
    authenticated = false;
    await page.getByRole('button', { name: 'Keluar', exact: true }).click();
    if (![200, 204].includes((await loggedOut).status())) throw new Error('Logout failed');
    await page.waitForURL('https://ftth.karuhundeveloper.com/login');
    report.logoutPassed = true;
    fs.writeFileSync(path.join(evidence, 'page-errors.json'), JSON.stringify(pageErrors));
    fs.writeFileSync(path.join(evidence, 'post-login-api-errors.json'), JSON.stringify(afterLoginApiErrors));
    fs.writeFileSync(path.join(evidence, 'business-mutation-requests.json'), JSON.stringify(businessMutationRequests));
    if (pageErrors.length || afterLoginApiErrors.length || businessMutationRequests.length) throw new Error('Public browser reported JavaScript/API errors or unexpected business writes');
    report.businessMutationRequests = businessMutationRequests.length;
    report.pageErrorCount = 0; report.authenticatedApiErrorCount = 0;
    report.status = 'PASS';
    await context.close();
  } catch (error) {
    report.status = 'FAIL'; report.failureType = error.name;
    fs.writeFileSync(path.join(evidence, 'private-error.txt'), String(error.stack || error));
  } finally {
    if (browser) await browser.close();
    report.finishedAtUtc = new Date().toISOString();
    report.sourceSha256 = crypto.createHash('sha256').update(fs.readFileSync(__filename)).digest('hex');
    fs.writeFileSync(path.join(evidence, 'verification.json'), JSON.stringify(report, null, 2) + '\n');
    fs.writeFileSync(path.join(evidence, 'exit-code.txt'), report.status === 'PASS' ? '0\n' : '1\n');
  }
  console.log('Public browser smoke ' + report.status + '; private evidence ' + evidence);
  process.exitCode = report.status === 'PASS' ? 0 : 1;
})();
